 assert.equal(await page.evaluate(()=>previewAngle),saved.angle);
 assert.equal(await page.evaluate(()=>previewZoom),saved.zoom);
 await page.locator('[data-language="en"]').click();
 assert.equal(await page.locator('#start-camera-heading').textContent(),'Starting view');
 await page.setViewportSize({width:960,height:800});
 await page.locator('#save-start-camera').scrollIntoViewIfNeeded();
 const buttons=await page.locator('.start-camera-actions button').first().boundingBox();
 assert.ok(buttons.x>=0&&buttons.x+buttons.width<=960);
 await page.screenshot({path:'artifacts/start-camera-editor.png'});
 await page.locator('#play').click();
 await page.waitForFunction(()=>typeof camera!=='undefined'&&sceneRenderer.ready&&!loadingActive&&cameraIntro===null);
 assert.ok(await page.evaluate(()=>Math.abs(angle-Math.PI/3)<1e-10&&camera.pitch===37));
 assert.deepEqual(await page.evaluate(()=>definition.camera),expected);
 assert.deepEqual(errors,[]);
 console.log('PASS starting view capture, history, export/import, preview restoration, localisation and gameplay');
