 await page.locator('#undo').click();assert.deepEqual(await page.evaluate(()=>model.map.camera),expected);
 const downloadPromise=page.waitForEvent('download');await page.locator('#export').click();
 const download=await downloadPromise,exported=JSON.parse(await fs.readFile(await download.path(),'utf8'));
 assert.deepEqual(exported.camera,expected);
 await page.locator('#file').setInputFiles({name:'starting-view.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
 await page.reload();await page.waitForFunction(()=>previewRenderer?.ready&&previewRuntime);
 assert.ok(await page.evaluate(()=>Math.abs(previewAngle-Math.PI/3)<1e-10&&previewCamera.pitch===37));
 const saved=await page.evaluate(()=>({camera:{...previewCamera},angle:previewAngle,zoom:previewZoom,map:JSON.stringify(model.map),history:model.undoStack.length}));
 await page.locator('#preview-start-camera').click();
 assert.equal(await page.locator('#preview-start-camera').getAttribute('aria-pressed'),'true');
 assert.equal(await page.locator('#save-start-camera').isDisabled(),true);
 assert.ok(await page.evaluate(()=>previewCamera.mode==='perspective'&&previewAngle>Math.PI/3));
 await page.waitForFunction(()=>startViewPreview?.elapsed>=1.5);
 assert.ok(await page.evaluate(()=>Math.abs(previewAngle-Math.PI/3)<1e-10&&previewCamera.pitch===37));
 assert.equal(await page.evaluate(()=>JSON.stringify(model.map)),saved.map);
 assert.equal(await page.evaluate(()=>model.undoStack.length),saved.history);
 await page.screenshot({path:'artifacts/start-camera-preview.png'});
 await page.locator('#preview-start-camera').click();
